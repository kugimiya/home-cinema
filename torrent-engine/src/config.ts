import { z } from "zod";

const envBool = (v: string | undefined, fallback: boolean): boolean => {
  if (v === undefined || v === "") return fallback;
  return v === "1" || v.toLowerCase() === "true";
};

const envInt = (v: string | undefined, fallback: number): number => {
  if (v === undefined || v === "") return fallback;
  const n = Number.parseInt(v, 10);
  return Number.isFinite(n) ? n : fallback;
};

const envFloat = (v: string | undefined, fallback: number): number => {
  if (v === undefined || v === "") return fallback;
  const n = Number.parseFloat(v);
  return Number.isFinite(n) ? n : fallback;
};

const envStr = (v: string | undefined, fallback: string): string =>
  v !== undefined && v !== "" ? v : fallback;

const envStrOrNull = (v: string | undefined, fallback: string | null): string | null => {
  if (v === undefined) return fallback;
  if (v === "") return null;
  return v;
};

